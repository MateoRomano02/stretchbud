#!/bin/sh
# Embeds web/assets/bud.glb as base64 in web/assets/bud.glb.js (window.BUD_GLB_B64), so the
# page can load the character with a classic <script> tag: WKWebView may refuse fetch/XHR of
# file:// URLs. Run after replacing bud.glb.
set -eu
cd "$(dirname "$0")/.."
{
  printf '/* Generated by scripts/embed-glb.sh from web/assets/bud.glb (Quaternius, CC0 1.0). Do not edit. */\n'
  printf 'window.BUD_GLB_B64 = "'
  base64 < web/assets/bud.glb | tr -d '\n'
  printf '";\n'
} > web/assets/bud.glb.js
ls -l web/assets/bud.glb web/assets/bud.glb.js
